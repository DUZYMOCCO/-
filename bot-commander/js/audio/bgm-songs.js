export const barSeconds = track => (60 / track.bpm) * BEATS_PER_BAR;
export const trackSeconds = track => barSeconds(track) * track.bars;

/** 1 小節ぶんの音（t は小節の頭からの秒、len は秒）。bar は何周目でもよい（loop の時は bars で割った余り）。 */
export function trackEvents(track, bar) {
  const b = ((bar % track.bars) + track.bars) % track.bars;
  const beat = 60 / track.bpm;
  const ev = [];
  for (const layer of LAYERS) {
    for (const [eb, at, note, len, vel] of track[layer] || []) {
      if (eb !== b) continue;
      ev.push({ kind: layer, t: at * beat, note, len: len * beat, vel });
    }
  }
  return ev.sort((a, c) => a.t - c.t);
}

/** 曲データの書き間違いを探す（見つけた問題の文字の配列。空なら OK）。 */
export function validateTrack(track, id = '?') {
  const bad = [];
  const say = m => bad.push(`${id}: ${m}`);
  if (!(track.bpm >= 40 && track.bpm <= 120)) say(`bpm ${track.bpm}`);
  if (!(Number.isInteger(track.bars) && track.bars >= 1 && track.bars <= 64)) say(`bars ${track.bars}`);
  if (typeof track.loop !== 'boolean') say('loop');
  for (const k of ['wind', 'reverb']) if (!(track[k] >= 0 && track[k] <= 1)) say(`${k} ${track[k]}`);
  for (const layer of LAYERS) {
    const list = track[layer];
    if (!Array.isArray(list)) { say(`${layer} がない`); continue; }
    list.forEach((e, i) => {
      const [bar, at, note, len, vel] = e;
      const where = `${layer}[${i}]`;
      if (e.length !== 5) say(`${where} の長さ ${e.length}`);
      if (!(Number.isInteger(bar) && bar >= 0 && bar < track.bars)) say(`${where} bar ${bar}`);
      if (!(at >= 0 && at < BEATS_PER_BAR)) say(`${where} beat ${at}`);
      if (!(len > 0 && len <= 16)) say(`${where} len ${len}`);
      if (!(vel > 0 && vel <= 1)) say(`${where} vel ${vel}`);
      const notes = layer === 'pad' ? note : [note];
      if (layer === 'pad' && !Array.isArray(note)) say(`${where} pad の音は配列`);
      else if (layer === 'pulse') { if (note !== 0 && note !== 1) say(`${where} pulse の種類 ${note}`); }
      else for (const n of notes) if (!(Number.isInteger(n) && n >= 28 && n <= 96)) say(`${where} midi ${n}`);
    });
  }
  return bad;
}
